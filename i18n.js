// A MutationObserver keeps doing it for everything the scripts change later.

const I18N_LANG = (() => {
  try {
    const s = JSON.parse(localStorage.getItem('settings') || '{}');
    if (s.lang === 'ru' || s.lang === 'en') return s.lang;
  } catch {}
  return /^(ru|uk|be|kk)/i.test(navigator.language) ? 'ru' : 'en';
})();

