const I18N_CYR = /[А-Яа-яЁё]/;

function i18nText(s) {
  if (I18N_LANG !== 'en' || !s || !I18N_CYR.test(s)) return s;
  const lead = s.match(/^\s*/)[0];
  const trail = s.slice(lead.length).match(/\s*$/)[0];
  const core = s.slice(lead.length, s.length - trail.length);
  if (Object.prototype.hasOwnProperty.call(I18N_EN, core)) return lead + I18N_EN[core] + trail;
  for (const [re, rep] of I18N_PATTERNS) {
    if (re.test(core)) return lead + core.replace(re, rep) + trail;
  }
  return s;
}

const I18N_ATTRS = ['title', 'placeholder', 'data-tip', 'label'];

function i18nNode(n) {
  if (n.nodeType === Node.TEXT_NODE) {
    const t = i18nText(n.nodeValue);
    if (t !== n.nodeValue) n.nodeValue = t;
    return;
  }
  if (n.nodeType !== Node.ELEMENT_NODE) return;
  for (const a of I18N_ATTRS) {
    const v = n.getAttribute(a);
    if (v && I18N_CYR.test(v)) {
      const t = i18nText(v);
      if (t !== v) n.setAttribute(a, t);
    }
  }
}

function i18nTree(root) {
  i18nNode(root);
  const walk = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  while (walk.nextNode()) i18nNode(walk.currentNode);
}

if (I18N_LANG === 'en') {
  document.documentElement.lang = 'en';
  i18nTree(document.body);
  document.title = i18nText(document.title);
  new MutationObserver(list => {
    for (const m of list) {
      if (m.type === 'characterData') i18nNode(m.target);
      else if (m.type === 'attributes') i18nNode(m.target);
      else for (const n of m.addedNodes) i18nTree(n);
    }
  }).observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: I18N_ATTRS });
  new MutationObserver(() => {
    const t = i18nText(document.title);
    if (t !== document.title) document.title = t;
  }).observe(document.querySelector('title'), { childList: true, characterData: true, subtree: true });
}
